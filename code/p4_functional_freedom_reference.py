#!/usr/bin/env python3
"""Reference diagnostic for P4 functional freedom.

This is deliberately a minimal algebraic self-test, not a full graviton-amplitude
basis generator.  For massless four-point kinematics s+t+u=0, the ring of fully
crossing-symmetric scalar polynomials is generated by

    sigma2 = s^2 + t^2 + u^2
    sigma3 = s*t*u

so monomials sigma2**a * sigma3**b have Mandelstam degree 2*a+3*b.
If a proposed structural principle fixes only finitely many low-degree data while
leaving higher crossing-symmetric contact coefficients unrestricted, the number
of admissible coefficient directions grows with the hard/EFT cutoff.  That is a
constructive witness for the FUNCTIONAL_FREEDOM_BLOCKED classification.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Iterable, List


@dataclass(frozen=True)
class SymmetricMonomial:
    a: int
    b: int

    @property
    def degree(self) -> int:
        return 2 * self.a + 3 * self.b

    @property
    def label(self) -> str:
        parts = []
        if self.a:
            parts.append("sigma2" if self.a == 1 else f"sigma2^{self.a}")
        if self.b:
            parts.append("sigma3" if self.b == 1 else f"sigma3^{self.b}")
        return "*".join(parts) if parts else "1"


def crossing_symmetric_basis(max_degree: int, min_degree: int = 0) -> List[SymmetricMonomial]:
    """Enumerate sigma2^a sigma3^b with min_degree <= 2a+3b <= max_degree."""
    if max_degree < 0 or min_degree < 0:
        raise ValueError("degrees must be non-negative")
    if min_degree > max_degree:
        return []

    out: List[SymmetricMonomial] = []
    for b in range(max_degree // 3 + 1):
        for a in range(max_degree // 2 + 1):
            monomial = SymmetricMonomial(a=a, b=b)
            if min_degree <= monomial.degree <= max_degree:
                out.append(monomial)
    return sorted(out, key=lambda x: (x.degree, x.b, x.a))


def freedom_count(max_degree: int, fixed_through_degree: int) -> int:
    """Lower-bound count when all coefficients through a finite degree are fixed.

    The retained scalar coefficient directions have degree strictly above
    ``fixed_through_degree``.  A real gravity/helicity analysis must also multiply
    by the allowed physical tensor/contact basis and impose its exact constraints;
    this routine only demonstrates the scalar crossing-symmetric growth mechanism.
    """
    return len(crossing_symmetric_basis(max_degree, fixed_through_degree + 1))


def growth_sequence(cutoffs: Iterable[int], fixed_through_degree: int) -> List[int]:
    return [freedom_count(cutoff, fixed_through_degree) for cutoff in cutoffs]


def classify_growth(cutoffs: Iterable[int], fixed_through_degree: int) -> str:
    values = growth_sequence(cutoffs, fixed_through_degree)
    if len(values) < 2:
        return "INSUFFICIENT_CUTOFF_SEQUENCE"
    if all(y > x for x, y in zip(values, values[1:])):
        return "FUNCTIONAL_FREEDOM_GROWTH_WITNESS"
    if values[-1] > values[0]:
        return "FUNCTIONAL_FREEDOM_NONDECREASING_WITNESS"
    return "NO_GROWTH_WITNESS_AT_TESTED_CUTOFFS"


def self_test() -> None:
    # Exact low-degree ring checks.
    labels_6 = {m.label for m in crossing_symmetric_basis(6)}
    expected = {"1", "sigma2", "sigma3", "sigma2^2", "sigma2*sigma3", "sigma2^3", "sigma3^2"}
    assert labels_6 == expected, (labels_6, expected)

    # If all data through degree 3 are frozen, new crossing-symmetric directions
    # keep appearing as the cutoff is raised.
    cutoffs = [4, 6, 8, 10, 12, 18, 24, 30]
    counts = growth_sequence(cutoffs, fixed_through_degree=3)
    assert counts == [1, 4, 7, 11, 16, 34, 58, 88], counts
    assert classify_growth(cutoffs, 3) == "FUNCTIONAL_FREEDOM_GROWTH_WITNESS"

    # Freezing any finite degree only delays the growth; it does not remove the
    # infinite tower if no additional microscopic selector is supplied.
    delayed = growth_sequence([12, 18, 24, 30], fixed_through_degree=11)
    assert delayed == [2, 20, 44, 74], delayed
    assert delayed[-1] > delayed[0]

    print("p4_functional_freedom_reference: PASS")
    print("cutoffs=", cutoffs)
    print("FF_D(fixed_through_degree=3)=", counts)
    print("classification=FUNCTIONAL_FREEDOM_GROWTH_WITNESS")


if __name__ == "__main__":
    self_test()
